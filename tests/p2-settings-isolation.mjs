import assert from 'node:assert/strict';
import {applyEditedSettings} from '../core/settings-delta.js';
const draft={top_k:3,enabled:false,temporal_decay:{minRelevance:0.3,rate:1},collections:{chatA:{enabled:true}},lastUsed:'old'};
const baseline=structuredClone(draft);
const state=structuredClone(draft);
state.collections.chatA.enabled=false;
state.collections.chatB={enabled:true};
state.top_k=9;
state.temporal_decay.rate=2;
draft.enabled=true;
draft.temporal_decay.minRelevance=0;
applyEditedSettings(draft,state,baseline);
assert.equal(state.top_k,9,'Unedited top-K must not be reset by stale form');
assert.equal(state.collections.chatA.enabled,false,'Never reset collection A');
assert.deepEqual(state.collections.chatB,{enabled:true},'Never remove new collection B');
assert.equal(state.temporal_decay.minRelevance,0,'Valid zero is retained');
assert.equal(state.temporal_decay.rate,2,'Unrelated nested edit is retained');
assert.equal(draft.top_k,9,'Future callbacks must not keep a stale value');
assert.equal(state.enabled,true);
draft.top_k=0;
applyEditedSettings(draft,state,baseline);
assert.equal(state.top_k,0);
assert.equal(state.collections.chatB.enabled,true);
console.log('PASS: delta saves preserve independent collection metadata and valid zero/false');
